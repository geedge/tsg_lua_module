int main()
{
    int i = 0;
    tsg_lua_handle lua[THREAD_NUM] = {0};
    pthread_t thread[THREAD_NUM] = {0};
    struct timespec time_start, time_end;
    long time1  = 0, time2 = 0, time3 = 0, time4 = 0, time5 = 0;

    content_len = strlen(content);

    for (i = 0; i < THREAD_NUM; i++)
    {
        lua[i] = tsg_lua_vm_create();
        if (lua[i] == NULL)
        {
            return -1;
        }
    }

    /* tsg_lua_exec 运行luajit文本脚本 */
    get_script_buffer("./multithread_test.lua");
    clock_gettime(CLOCK_REALTIME, &time_start);
    for (i = 0; i < THREAD_NUM; i++)
    {
        pthread_create(&thread[i], NULL, test_tsg_lua_exec, lua[i]);
    }
    for (i = 0; i < THREAD_NUM; i++)
    {
        pthread_join(thread[i], NULL);
    }
    clock_gettime(CLOCK_REALTIME, &time_end);
    time1 = calc_time(time_start, time_end);
    time1 /= 10000;
    printf("text script buffer:%ld\n", time1);
    sleep(1);

    /* tsg_lua_exec 运行luajit 字节码脚本 */
    get_script_buffer("./multithread_test.luajit");
    clock_gettime(CLOCK_REALTIME, &time_start);
    for (i = 0; i < THREAD_NUM; i++)
    {
        pthread_create(&thread[i], NULL, test_tsg_lua_exec, lua[i]);
    }
    for (i = 0; i < THREAD_NUM; i++)
    {
        pthread_join(thread[i], NULL);
    }
    clock_gettime(CLOCK_REALTIME, &time_end);
    time2 = calc_time(time_start, time_end);
    time2 /= 10000;
    printf("bytecode script buffer:%ld\n", time2);
    sleep(1);

    /* tsg_cache_exec 运行lua文本脚本 */
    get_script_buffer("./multithread_test.lua");
    clock_gettime(CLOCK_REALTIME, &time_start);
    for (i = 0; i < THREAD_NUM; i++)
    {
        pthread_create(&thread[i], NULL, test_tsg_cache_exec, lua[i]);
    }
    for (i = 0; i < THREAD_NUM; i++)
    {
        pthread_join(thread[i], NULL);
    }
    clock_gettime(CLOCK_REALTIME, &time_end);
    time3 = calc_time(time_start, time_end);
    time3 /= 10000;
    printf("cache text script buffer:%ld\n", time3);
    sleep(1);

    /* tsg_lua_exec 运行lua文本脚本 */
    get_script_buffer("./multithread_test.luajit");
    clock_gettime(CLOCK_REALTIME, &time_start);
    for (i = 0; i < THREAD_NUM; i++)
    {
        pthread_create(&thread[i], NULL, test_tsg_cache_exec, lua[i]);
    }
    for (i = 0; i < THREAD_NUM; i++)
    {
        pthread_join(thread[i], NULL);
    }
    clock_gettime(CLOCK_REALTIME, &time_end);
    time4 = calc_time(time_start, time_end);
    time4 /= 10000;
    printf("cache bytecode script buffer:%ld\n", time4);
    sleep(1);

    clock_gettime(CLOCK_REALTIME, &time_start);
    for (i = 0; i < THREAD_NUM; i++)
    {
        pthread_create(&thread[i], NULL, test_c_func, lua[i]);
    }
    for (i = 0; i < THREAD_NUM; i++)
    {
        pthread_join(thread[i], NULL);
    }
    clock_gettime(CLOCK_REALTIME, &time_end);
    time5 = calc_time(time_start, time_end);
    time5 /= 10000;
    printf("C func:%ld\n", time5);

    printf("text script buffer / C func:%lf%%\n", time1 * 100.00 / time5);
    printf("bytecode script buffer / C func:%lf%%\n", time2 * 100.00 / time5);
    printf("cache text script buffer / C func:%lf%%\n", time3 * 100.00 / time5);
    printf("cache bytecode script buffer / C func:%lf%%\n", time4 * 100.00 / time5);
    return 0;
}
