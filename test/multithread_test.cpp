static char *get_script_buffer(const char *file)
{
    FILE *fp = fopen(file, "r");
    if (fp)
    {
        int num = fread(script, 1, 4096, fp);
        if (num != 0)
        {
            script[num] = 0;
            script_len = num;
            return script;
        }
    }
    return NULL;
}

static void *test_tsg_lua_exec(void *ptr)
{
    char out[255];
    size_t out_len = 0;
    size_t out_type = 0;
    memset(out, 0, sizeof(out));
    tsg_lua_handle L = (tsg_lua_handle)ptr;
    int i = 0;

    for (i = 0; i < 10000; i++)
    {
        tsg_lua_exec(L, script, script_len, content, content_len, out, &out_len, &out_type);
    }
    pthread_exit(NULL);
}

static void *test_tsg_cache_exec(void *ptr)
{
    char out[255];
    size_t out_len = 0;
    size_t out_type = 0;
    memset(out, 0, sizeof(out));
    tsg_lua_handle L = (tsg_lua_handle)ptr;
    int i = 0;

    int script_id = tsg_lua_cache_script(L, script, script_len);
    for (i = 0; i < 10000; i++)
    {
        tsg_cache_exec(L, script_id, content, content_len, out, &out_len, &out_type);
    }
    pthread_exit(NULL);
}

